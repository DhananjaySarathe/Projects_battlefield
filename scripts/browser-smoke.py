"""Run against `npm run dev`. Requires Playwright Python and a Chromium executable."""
import base64
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':1080})
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:5173/',wait_until='networkidle')
    expect(page.locator('.product-card')).to_have_count(8)
    page.screenshot(path=str(ROOT/'docs/desktop-preview.png'))
    page.get_by_role('button',name='Vote for formly',exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_label('Your name',exact=True).fill('Jordan Lee')
    page.get_by_role('button',name='Join the community',exact=True).click()
    expect(page.get_by_role('dialog')).to_have_count(0)
    formly_vote=page.get_by_role('button',name='Vote for formly',exact=True)
    formly_vote.click()
    expect(formly_vote).to_have_attribute('aria-pressed','true')
    expect(formly_vote).to_contain_text('249')
    formly_vote.click()
    expect(formly_vote).to_have_attribute('aria-pressed','false')
    expect(formly_vote).to_contain_text('248')
    page.get_by_role('button',name='Save formly',exact=True).click()
    expect(page.get_by_role('button',name='Save formly',exact=True)).to_have_attribute('aria-pressed','true')
    page.locator('.sidebar').get_by_role('button',name='Saved products',exact=True).click()
    expect(page.locator('.product-card')).to_have_count(1)
    page.get_by_role('button',name='Meet formly',exact=True).click()
    page.get_by_role('button',name='Claim trial',exact=True).click()
    expect(page.get_by_role('button',name='Claimed ✓')).to_be_visible()
    expect(page.locator('.detail-offer code')).to_contain_text('BF-')
    page.get_by_role('button',name='Try the sample preview',exact=True).click()
    page.get_by_label('Your idea',exact=True).fill('A product for independent artists')
    page.get_by_role('button',name='Let’s explore it').click()
    expect(page.get_by_text('Your idea is in good company.')).to_be_visible()
    page.get_by_role('button',name='Close dialog').click()
    page.get_by_role('tab',name='Reviews').click()
    page.get_by_role('button',name='4 star rating',exact=True).click()
    page.get_by_role('textbox',name='Feedback').fill('The forms are easy to set up and the design feels thoughtful.')
    page.get_by_role('button',name='Post review',exact=True).click()
    expect(page.get_by_text('The forms are easy to set up and the design feels thoughtful.')).to_be_visible()
    page.get_by_role('tab',name='Discussion').click()
    page.get_by_role('textbox',name='Feedback').fill('Does it support exporting responses?')
    page.get_by_role('button',name='Post comment',exact=True).click()
    expect(page.get_by_text('Does it support exporting responses?')).to_be_visible()
    page.locator('.feedback-item').filter(has_text='Maya Chen').get_by_role('button',name='Reply',exact=True).click()
    page.get_by_role('textbox',name='Feedback').fill('Thanks for sharing the story behind it!')
    page.get_by_role('button',name='Post comment',exact=True).click()
    expect(page.locator('.feedback-item.reply')).to_have_count(1)
    page.keyboard.press('Escape')
    page.locator('.sidebar').get_by_role('button',name='Launch a product').click()
    page.get_by_label('Product name',exact=True).fill('Kindred')
    page.get_by_label('One-line pitch',exact=False).fill('A useful home for community ideas.')
    page.get_by_label('The story behind your product',exact=True).fill('Kindred helps neighborhood communities collect ideas and organize useful projects together.')
    page.get_by_label('Product website',exact=True).fill('https://example.com')
    page.get_by_label('Tags',exact=False).fill('Community, Collaboration')
    page.get_by_label('Trial offer',exact=True).fill('7 days free')
    page.get_by_label('Available spots',exact=True).fill('2')
    page.locator('.upload-zone').nth(1).locator('input').set_input_files({'name':'guide.txt','mimeType':'text/plain','buffer':b'Kindred community starter guide.'})
    page.get_by_role('button',name='Launch product',exact=True).click()
    expect(page.locator('.detail-header')).to_contain_text('Kindred')
    expect(page.locator('.detail-bottom').get_by_role('link',name='Download resource')).to_have_attribute('href','data:text/plain;base64,'+base64.b64encode(b'Kindred community starter guide.').decode())
    page.get_by_role('button',name='Edit product').click()
    page.get_by_label('One-line pitch',exact=False).fill('A better home for community ideas.')
    page.get_by_role('button',name='Save changes',exact=True).click()
    expect(page.locator('.detail-header')).to_contain_text('A better home for community ideas.')
    page.get_by_role('tab',name='Bug reports').click()
    page.get_by_role('textbox',name='Feedback').fill('Open the settings page and click save. The panel stays loading indefinitely.')
    page.get_by_role('button',name='Report bug',exact=True).click()
    expect(page.locator('.bug-state')).to_contain_text('Open')
    page.get_by_role('button',name='Mark resolved').click()
    expect(page.locator('.bug-state')).to_contain_text('Resolved')
    page.keyboard.press('Escape')
    page.locator('.sidebar').get_by_role('button',name='Leaderboard',exact=True).click()
    expect(page.locator('.leader-row')).to_have_count(9)
    page.get_by_label('Leaderboard date').fill('2020-01-01')
    expect(page.locator('.empty-state')).to_contain_text('Nothing here just yet.')
    page.locator('.sidebar').get_by_role('button',name='Discover',exact=True).click()
    page.get_by_label('Search products').fill('Kindred')
    expect(page.locator('.product-card')).to_have_count(1)
    page.reload(wait_until='networkidle')
    expect(page.locator('.product-card').filter(has_text='Kindred')).to_have_count(1)
    expect(page.locator('.profile-button')).to_contain_text('Jordan Lee')
    mobile=context.new_page()
    mobile.set_viewport_size({'width':390,'height':844})
    mobile.goto('http://127.0.0.1:5173/',wait_until='networkidle')
    assert mobile.evaluate('document.documentElement.scrollWidth<=window.innerWidth'), 'Mobile horizontal overflow'
    mobile.screenshot(path=str(ROOT/'docs/mobile-preview.png'))
    mobile.locator('.mobile-nav').get_by_role('button',name='Launch',exact=True).click()
    expect(mobile.get_by_role('dialog')).to_be_visible()
    assert mobile.evaluate('document.documentElement.scrollWidth<=window.innerWidth'), 'Dialog horizontal overflow'
    mobile.keyboard.press('Escape')
    mobile.locator('.mobile-nav').get_by_role('button',name='Saved',exact=True).click()
    expect(mobile.locator('.product-card')).to_have_count(1)
    assert not errors, errors
    print('PASS: auth, votes, saves, claims, playground, reviews, replies, launch, upload/download, edit, bug resolution, rankings, archives, search, persistence, desktop/mobile overflow, keyboard dismissal; no browser runtime errors.')
    browser.close()
